"""Our own sound effects, synthesized from sine waves and noise (no third-party audio).

Every clip opens with the same 1-second sting so the series feels like one show.
Sources are recorded in video/README.md: all sounds are generated by this file.
"""
import math
import random

GAIN = {'sting': 0.30, 'pop': 0.22, 'click': 0.26, 'whoosh': 0.16, 'boing': 0.24}


def _env(i, n, attack=0.01, rate=24000):
    a = int(attack * rate)
    return (i / a if i < a else 1.0) * (1 - i / n) ** 2


def sound(kind, rate):
    rnd = random.Random(kind)  # deterministic noise
    if kind == 'sting':          # two rising, bell-like notes
        out = []
        for start, freq, length in ((0.0, 659.25, 0.45), (0.22, 987.77, 0.78)):
            n = int(length * rate)
            note = [math.sin(2 * math.pi * freq * i / rate) + 0.35 * math.sin(4 * math.pi * freq * i / rate)
                    for i in range(n)]
            note = [v * _env(i, n, 0.005, rate) for i, v in enumerate(note)]
            out = _place(out, note, int(start * rate))
        return out
    if kind == 'pop':            # quick upward blip
        n = int(0.09 * rate)
        return [math.sin(2 * math.pi * (380 + 2600 * i / n) * i / rate) * _env(i, n, 0.003, rate) for i in range(n)]
    if kind == 'click':          # short tick with a little body
        n = int(0.045 * rate)
        return [(0.6 * math.sin(2 * math.pi * 1800 * i / rate) + 0.4 * (rnd.random() * 2 - 1)) * (1 - i / n) ** 4
                for i in range(n)]
    if kind == 'whoosh':         # filtered noise swelling and fading
        n, level, out = int(0.42 * rate), 0.0, []
        for i in range(n):
            level += 0.08 * ((rnd.random() * 2 - 1) - level)
            out.append(3.0 * level * math.sin(math.pi * i / n))
        return out
    if kind == 'boing':          # falling wobble for "that doesn't fit"
        n = int(0.35 * rate)
        return [math.sin(2 * math.pi * (520 - 260 * i / n) * i / rate + 3 * math.sin(2 * math.pi * 18 * i / rate))
                * _env(i, n, 0.004, rate) for i in range(n)]
    raise ValueError(kind)


def _place(base, part, offset):
    if len(base) < offset + len(part):
        base = base + [0.0] * (offset + len(part) - len(base))
    for i, v in enumerate(part):
        base[offset + i] += v
    return base


def mix(samples, rate, cues):
    """Add sound cues [(seconds, kind)] onto 16-bit samples (an array('h')), in place."""
    cache = {}
    for t, kind in cues:
        wave = cache.setdefault(kind, sound(kind, rate))
        start = int(t * rate)
        gain = GAIN[kind] * 32767
        for i, v in enumerate(wave):
            j = start + i
            if j >= len(samples):
                break
            samples[j] = max(-32768, min(32767, int(samples[j] + v * gain)))
    return samples
