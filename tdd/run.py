"""TDD evidence for Shivaths Karne's commits.

Each tdd/NN_<name>.(py|mjs) test was committed on its own, right before the code commit it drives.
For every test this script finds that test commit and the code commit after it, checks out both
(git archive into a temp folder), runs the test against each with REPO=<that checkout>, and requires:
  test commit -> FAIL (red: the behaviour did not exist yet)
  code commit -> PASS (green: the code made it pass)
Results go to tdd/evidence.md. Exit 1 if any test is not red-then-green.

  python tdd/run.py              all tests
  python tdd/run.py heartbeat    only tests whose name contains this text

Tests import code from $REPO, so a test can be run alone against any checkout:
  REPO=. python tdd/11_heartbeat_event.py
Tooling (vite, puppeteer-core) always comes from this checkout's web/node_modules (npm install in web/).
Tests describe behaviour as of their commit; a later commit may change it (e.g. BUILD_ID), so they are
judged at their own commit, not at HEAD."""
import glob
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TMP = tempfile.mkdtemp(prefix="clipcademy-tdd-")
_checkouts = {}


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()


def checkout(rev):
    """The tree at rev, without lecture PDFs and rendered clips (no test reads them)."""
    sha = git("rev-parse", "--short", rev)
    if sha not in _checkouts:
        dest, tar = os.path.join(TMP, sha), os.path.join(TMP, sha + ".tar")
        git("archive", "--format=tar", "-o", tar, sha, "--", ".", ":(exclude)Notes", ":(exclude)video/media")
        with tarfile.open(tar) as t:
            t.extractall(dest, filter="data")
        _checkouts[sha] = dest
    return sha, _checkouts[sha]


def run(test, repo):
    cmd = [sys.executable, test] if test.endswith(".py") else ["node", test]
    p = subprocess.run(cmd, cwd=ROOT, env={**os.environ, "REPO": repo, "PYTHONDONTWRITEBYTECODE": "1"},
                       capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=180)
    lines = [l.strip() for l in (p.stdout + p.stderr).splitlines() if l.strip()]
    # the first exception line names why it failed: "KeyError: 'x'", "AssertionError [ERR_ASSERTION]: ..."
    reason = next((l for l in lines if re.match(r"^(?:[A-Z]\w*)?(?:Error|Exception)\b", l)), lines[-1] if lines else "")
    for path in (repo, ROOT):
        for form in (path + os.sep, path.replace("\\", "\\\\") + "\\\\", pathlib.Path(path).as_uri() + "/"):
            reason = reason.replace(form, "")
    return p.returncode == 0, reason.replace("|", "/")[:160]


def test_and_code_commits(name):
    """The commit that added tdd/<name>, and its child: the code commit the test was written for."""
    test_sha = git("log", "--diff-filter=A", "--format=%H", "HEAD", "--", f"tdd/{name}").splitlines()[-1]
    child = next(line.split()[0] for line in git("rev-list", "--parents", "HEAD").splitlines() if test_sha in line.split()[1:])
    return test_sha, child


def main():
    only = sys.argv[1] if len(sys.argv) > 1 else ""
    tests = sorted(t for t in glob.glob(os.path.join(HERE, "[0-9]*_*.*")) if only in os.path.basename(t))
    rows, ok_all = [], True
    for test in tests:
        name = os.path.basename(test)
        test_sha, code_sha = test_and_code_commits(name)
        subject = git("log", "-1", "--format=%s", code_sha)
        parent_sha, parent = checkout(test_sha)
        sha, commit = checkout(code_sha)
        parent_pass, why_red = run(test, parent)
        commit_pass, why_green = run(test, commit)
        ok = not parent_pass and commit_pass
        ok_all &= ok
        print(f"{'ok  ' if ok else 'BAD '} {parent_sha} -> {sha} {name}: test commit {'PASS' if parent_pass else 'FAIL'}, "
              f"code commit {'PASS' if commit_pass else 'FAIL'}")
        if not ok:
            print(f"      test commit: {why_red}\n      code commit: {why_green}")
        rows.append(f"| {sha} | {subject.replace('|', '/')} | `{name}` | {'FAIL' if not parent_pass else '**PASS**'} ({parent_sha}): {why_red} "
                    f"| {'PASS' if commit_pass else '**FAIL**'} |")
    if not only:
        with open(os.path.join(HERE, "evidence.md"), "w", encoding="utf-8") as f:
            f.write("# TDD evidence\n\nGenerated by `python tdd/run.py`. Each test was committed just before its code commit: "
                    "it fails at the test commit (red) and passes at the code commit (green).\n\n"
                    "| Code commit | Subject | Test | Test commit (red) and why | Code commit (green) |\n"
                    "|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
    print("all red -> green" if ok_all else "some tests are not red -> green")
    shutil.rmtree(TMP, ignore_errors=True)
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
